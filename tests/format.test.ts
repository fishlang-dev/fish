// Each snippet, valid TypeScript (or JavaScript for the babel parser), is formatted by Fish and
// by Prettier, and the two must agree.
async function agree(cases: string[], parser = "typescript") {
  for (const code of cases) {
    const expected = await prettier.format(code, { parser });
    expect([code, format(code)]).toEqual([code, expected]);
  }
}

// Where Fish prints other than Prettier on purpose: each row gives our text and the reason, and
// Prettier must really print something else.
async function differ(cases: [string, string, string][], parser = "typescript") {
  for (const [code, ours] of cases) {
    expect(await prettier.format(code, { parser })).not.toBe(ours);
    expect([code, format(code)]).toEqual([code, ours]);
  }
}

// The tree without its spans, to compare a program with its formatted text.
function shape(v: unknown): unknown {
  if (Array.isArray(v)) return v.map(shape);
  if (typeof v === "bigint") return `${v}n`;
  if (!v || typeof v !== "object") return v;
  return Object.fromEntries(Object.entries(v).filter(([k]) => k !== "start" && k !== "end").map(([k, x]) => [k, shape(x)]));
}

// Each snippet formats to text that parses back to the same tree, and formats again unchanged.
function roundTrip(cases: string[]) {
  for (const code of cases) {
    const out = format(code);
    expect([code, shape(parse(out))]).toEqual([code, shape(parse(code))]);
    expect([code, format(out)]).toEqual([code, out]);
  }
}

// Fish's own syntax has no Prettier output: each case gives the exact text expected, which must
// also format to itself.
function golden(cases: [string, string][]) {
  for (const [code, expected] of cases) {
    expect([code, format(code)]).toEqual([code, expected]);
    expect([expected, format(expected)]).toEqual([expected, expected]);
  }
}

