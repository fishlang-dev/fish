test("output the parser can't read back is the formatter's error, not the user's", () => {
  // The parser can't read a regex after `({ ... }) :` where an arrow could start, which the
  // formatter's output here has once the arrow loses its parentheses.
  const src = "x ? (() => ({ a: b })) : { a: c, [/re/g]: d };";
  let caught: unknown;
  try {
    format(src);
  } catch (e) {
    caught = e;
  }
  expect(caught).toBeInstanceOf(Error);
  expect(caught).not.toBeInstanceOf(CompileError);
  expect((caught as Error).message).toStartWith("the formatter produced output that doesn't parse");
});

test("bare bodies are found in time linear in the file", () => {
  const src = "if (a) b;\n".repeat(20000);
  const started = performance.now();
  expect(format(src)).toBe(src);
  expect(performance.now() - started).toBeLessThan(1000);
});

