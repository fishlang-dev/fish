// Generates src/casemap.ts: the C runtime's case tables, taken from JavaScript's own
// toUpperCase and toLowerCase and its Cased and Case_Ignorable properties, so Fish's case
// mapping matches the JavaScript engine that ran this. Run with `bun scripts/casemap.ts`.
import { writeFileSync } from "node:fs";
import { unicodeFingerprint } from "./unicode.ts";

type Simple = [number, number][];
type Special = [number, number[]][];

function mapping(change: (s: string) => string): [Simple, Special] {
  const simple: Simple = [];
  const special: Special = [];
  for (let cp = 0; cp <= 0x10ffff; cp++) {
    if (cp >= 0xd800 && cp < 0xe000) continue;
    const from = String.fromCodePoint(cp);
    const to = [...change(from)].map((c) => c.codePointAt(0)!);
    if (to.length === 1 && to[0] === cp) continue;
    // The runtime's tables hold at most three code points per mapping.
    if (to.length > 3) throw new Error(`U+${cp.toString(16)} maps to ${to.length} code points; widen the special tables`);
    if (to.length === 1) simple.push([cp, to[0]!]);
    else special.push([cp, to]);
  }
  return [simple, special];
}

function ranges(property: RegExp): [number, number][] {
  const found: [number, number][] = [];
  for (let cp = 0; cp <= 0x10ffff; cp++) {
    if (cp >= 0xd800 && cp < 0xe000) continue;
    if (!property.test(String.fromCodePoint(cp))) continue;
    const last = found.at(-1);
    if (last && last[1] === cp - 1) last[1] = cp;
    else found.push([cp, cp]);
  }
  return found;
}

const [upper, upperSpecial] = mapping((s) => s.toUpperCase());
const [lower, lowerSpecial] = mapping((s) => s.toLowerCase());
const pairs = (name: string, rows: [number, number][]) =>
  `static const uint32_t ${name}[][2] = {\n${rows.map(([a, b]) => `{0x${a.toString(16)},0x${b.toString(16)}}`).join(",").replace(/(.{100}[^,]*,)/g, "$1\n")}\n};\n`;
const specials = (name: string, rows: Special) =>
  `static const uint32_t ${name}[][4] = {\n${rows.map(([a, to]) => `{0x${a.toString(16)},${[...to, 0, 0].slice(0, 3).map((c) => `0x${c.toString(16)}`).join(",")}}`).join(",\n")}\n};\n`;

const c = [
  pairs("fsh_upper", upper),
  pairs("fsh_lower", lower),
  specials("fsh_upper_special", upperSpecial),
  specials("fsh_lower_special", lowerSpecial),
  pairs("fsh_cased", ranges(/\p{Cased}/u)),
  pairs("fsh_case_ignorable", ranges(/\p{Case_Ignorable}/u)),
].join("\n");

writeFileSync(
  new URL("../src/casemap.ts", import.meta.url),
  `// Generated by scripts/casemap.ts from JavaScript's case mapping; do not edit.\n// Each table is sorted by its first column, for binary search.\nexport const CASEMAP = String.raw\`\n${c}\`;\n\n// The Unicode version the tables were made from, by name and by scripts/unicode.ts's\n// fingerprint of its data.\nexport const CASEMAP_UNICODE = { version: ${JSON.stringify(process.versions.unicode ?? "unknown")}, fingerprint: ${JSON.stringify(unicodeFingerprint())} };\n`,
);
console.log(`upper ${upper.length}+${upperSpecial.length}, lower ${lower.length}+${lowerSpecial.length}`);
